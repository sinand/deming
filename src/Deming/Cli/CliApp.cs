using System.Reflection;

namespace Deming.Cli;

/// <summary>Entry point for the CLI role: talks to a running "deming serve" over HTTP (docs/scope.md § 5).</summary>
public static class CliApp
{
    public static int Run(string[] args, TextWriter stdout, TextWriter stderr) =>
        RunAsync(args, new CliContext { Out = stdout, Err = stderr, In = Console.In }).GetAwaiter().GetResult();

    public static async Task<int> RunAsync(string[] args, CliContext ctx)
    {
        if (args.Length == 0)
        {
            PrintUsage(ctx.Out);
            return ExitCodes.Success;
        }

        switch (args[0])
        {
            case "help" or "--help" or "-h":
                return Help(args.Skip(1).FirstOrDefault(), ctx);

            case "version" or "--version":
                ctx.Out.WriteLine(Version);
                return ExitCodes.Success;
        }

        var command = CliCommands.Find(args[0]);
        if (command is null)
        {
            ctx.Err.WriteLine($"Unknown command: {args[0]}");
            PrintUsage(ctx.Err);
            return ExitCodes.Error;
        }

        ParsedArgs parsed;
        try
        {
            parsed = ParsedArgs.Parse(args.Skip(1), command);
        }
        catch (CliException ex)
        {
            ctx.Err.WriteLine(ex.Message);
            return ex.ExitCode;
        }
        if (parsed.Has("help"))
        {
            ctx.Out.WriteLine(command.HelpText());
            return ExitCodes.Success;
        }

        if (command.Name != "install")
        {
            var warning = AgentInstall.Warning(ctx.Env);
            if (warning is not null)
                ctx.Err.WriteLine(warning);
        }

        using var run = new CliRun(ctx, command, parsed);
        try
        {
            return await command.Run(run);
        }
        catch (CliException ex)
        {
            ctx.Err.WriteLine(ex.Message);
            return ex.ExitCode;
        }
        catch (HttpRequestException ex) when (ex.InnerException is System.Security.Authentication.AuthenticationException { InnerException: { } cause })
        {
            // The handshake broke before the certificate was judged (the validation callback's refusal has no
            // inner exception): blaming the fingerprint here would send the user the wrong way.
            var reasons = new List<string>();
            for (Exception? e = cause; e is not null; e = e.InnerException)
                reasons.Add(e.Message);
            ctx.Err.WriteLine($"The TLS handshake with the server at {run.ServerUrl} failed before its certificate could be checked: {string.Join(" <- ", reasons).TrimEnd('.')}. "
                + "This is not a trust problem. A sandbox that restricts the process (some agent CLIs run commands in one) can cause it: run the command outside the sandbox.");
            return ExitCodes.Error;
        }
        catch (HttpRequestException ex) when (ex.InnerException is System.Security.Authentication.AuthenticationException)
        {
            ctx.Err.WriteLine($"The certificate of the server at {run.ServerUrl} is not trusted: {ex.InnerException!.Message} "
                + $"The CLI trusts the certificate 'deming serve' generated by its fingerprint ('{UserConfig.CertificateKey}' in {UserConfig.DefaultPath(ctx.Env)}): "
                + "start 'deming serve' with the same config file (DEMING_CONFIG) so it records it. A server with a certificate of its own needs one the system trusts.");
            return ExitCodes.Error;
        }
        catch (HttpRequestException ex)
        {
            ctx.Err.WriteLine($"Cannot reach the server at {run.ServerUrl}: {ex.Message}. Is 'deming serve' running? (DEMING_URL sets the address.)");
            return ExitCodes.Error;
        }
        catch (TaskCanceledException)
        {
            ctx.Err.WriteLine($"The server at {run.ServerUrl} did not answer in time.");
            return ExitCodes.Error;
        }
    }

    public static string Version =>
        typeof(CliApp).Assembly.GetCustomAttribute<AssemblyInformationalVersionAttribute>()?.InformationalVersion
        ?? "unknown";

    private static int Help(string? name, CliContext ctx)
    {
        if (name is null)
        {
            PrintUsage(ctx.Out);
            return ExitCodes.Success;
        }
        var command = CliCommands.Find(name);
        if (command is null)
        {
            ctx.Err.WriteLine($"Unknown command: {name}");
            return ExitCodes.Error;
        }
        ctx.Out.WriteLine(command.HelpText());
        return ExitCodes.Success;
    }

    private static void PrintUsage(TextWriter writer)
    {
        writer.WriteLine($"Deming {Version}");
        writer.WriteLine();
        writer.WriteLine("Usage:");
        writer.WriteLine("  deming serve          Start the server (panel + API)");
        writer.WriteLine("  deming <command>      Run a CLI command against the server");
        writer.WriteLine("  deming help <command> Usage and fields (flags and JSON) of one command");
        writer.WriteLine();
        writer.WriteLine("Commands:");
        foreach (var c in CliCommands.All)
            writer.WriteLine($"  {c.Name,-10}{c.Summary}");
        writer.WriteLine("  help      Show this help");
        writer.WriteLine("  version   Show the version");
        writer.WriteLine();
        writer.WriteLine("Exit codes: 0 success, 1 error, 3 nothing to do, 4 already exists.");
        writer.WriteLine("Project: name in the .deming file at the repository root (deming init <name>).");
        writer.WriteLine("Session: DEMING_SESSION_ID, otherwise CLAUDE_CODE_SESSION_ID.");
        writer.WriteLine("Server: DEMING_URL (https only, default https://127.0.0.1:5001); key: DEMING_API_KEY or the config file.");
    }
}
